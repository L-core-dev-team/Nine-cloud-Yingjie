"""Package the two already-scored outputs; this never reopens a holdout run."""
import argparse,hashlib,json
from pathlib import Path
root=Path(__file__).resolve().parents[3]
out=root/'docs/reports/evidence/YJ-P04-H3B2'
data=root/'packages/highlights/test/h3b2'
def save(name,obj):
    (out/(name+'.json')).write_bytes((json.dumps(obj,ensure_ascii=False,separators=(',',':'))+'\n').encode())
def main():
    global out
    ap=argparse.ArgumentParser()
    ap.add_argument('dev',type=Path);ap.add_argument('held',type=Path)
    ap.add_argument('--reserve',type=Path)
    args=ap.parse_args()
    manifest=json.loads((out/'freeze.json').read_bytes())
    partitions={'dev':args.dev,'held':args.held}
    if args.reserve:
        manifest['files'].update(json.loads((out/'reserve-freeze.json').read_bytes())['files'])
        partitions['reserve']=args.reserve
        out=out/'repair'
        out.mkdir(exist_ok=True)
    for name,sha in manifest['files'].items():assert hashlib.sha256((data/name).read_bytes()).hexdigest()==sha
    all_metrics={}; ranking={}; details={}; failure_index={}; stats={}
    for split,path in partitions.items():
        raw=path.read_bytes();run=json.loads(raw)
        assert run['part']==split
        corpus=[(s,f.name) for f in sorted(data.glob(split+'-*.jsonl')) for s in map(json.loads,f.read_bytes().splitlines())]
        assert [s['id'] for s,_ in corpus]==[r['id'] for r in run['results']]
        all_metrics[split]=run['totals']
        stats[split]=dict(stdoutSha256=hashlib.sha256(raw).hexdigest(),positive=0,review=0,ordinary=0,pairedOppositions=0,longArcs=0)
        details[split]=[];ranking[split]=[];errors=[]
        for i,(record,(story,file)) in enumerate(zip(run['results'],corpus),1):
            name=f'{split}-case-{i:02}'
            rows=story['rows'];g=stats[split]
            g['positive']+=sum(bool(r.get('event')) for r in rows);g['review']+=sum(bool(r.get('review')) for r in rows)
            g['ordinary']+=sum(not r.get('review') for r in rows)
            g['pairedOppositions']+=int(any(r.get('event') and r.get('claim')==earlier.get('claim') and earlier.get('verdict') in ('unresolved','contradicted') for j,r in enumerate(rows) for earlier in rows[:j]))
            g['longArcs']+=int(any(r.get('event') and r['asOf']-min(r['deps'])>=8 for r in rows))
            details[split].append(dict(id=story['id'],file=name+'.json',goldFile=file))
            save(name,dict(goldFile=file,**record))
            ranking[split].append(dict(story=story['id'],ranks=record['rank']))
            for row in record['rows']:
                if row['errors']:
                    errors.append(dict(story=story['id'],n=row['n'],arm=row['arm'],errors=row['errors'],trace=name+'.json'))
        save(split+'-failures',errors);failure_index[split]=dict(armRevisionFailures=len(errors),file=split+'-failures.json')
    save('proposal',dict(totals=all_metrics,counts='triples are TP, FP, FN; empty precision is null; review includes a routed hypothesis or an independently admitted fact',corpus=stats))
    save('propositions',dict(index=details,slots=['kind','actor','other','item','before','after','time','source','polarity','qualifier'],
        evidenceTuple=['revision','utf16Start','utf16End','sourceKey','narrativeSha256'],note='scope/session are generated by the stable synthetic host label ground-<story>; full quote in frozen goldFile at row and interval'))
    save('grounding',dict(bySplit={s:{k:{key:g[key] for key in ['matrix','rolePairs','slots','fact','confirmation','abstained','legalSpans','candidateOnly','top1','top3','ordered','pairs']} for k,g in groups.items()} for s,groups in all_metrics.items()},rankings=ranking,
        note='matrix rows are frozen whole-proposition verdicts; missing and wrong-fields counted separately. Earlier interfaces have no proposition verdict. outcome is narrower than whole entailment.'))
    save('failures',dict(allPerRevision=failure_index,ranking='grounding.json contains all expected and actual rankings including every ranking miss',
        historical='regression.json retains expected red causalAudit exit 1, and compares immutable H3-A/H3-B error files',
        firstBuild={'diagnostic':'TS5033 creating absent packages/contracts/dist; wrapper continued to print file content so compiler exit was not captured','retry':'create local output directory and rerun identical permission-restricted tsc','retryExit':0},
        firstDev={'command':'node --permission --allow-fs-read=* packages/highlights/h3b2/measure.mjs dev','nodeExit':0,'readerExit':1,'diagnostic':'historical imported evaluate.mjs also printed a JSON document; ConvertFrom-Json rejected two documents','fix':'use --split=dev and guarded main; before opening held'},
        firstSafety='../safety-first.json' if args.reserve else 'safety-first.json',independentReview='INDEPENDENT_HUMAN_BLIND_REVIEW_NOT_RUN'))
if __name__=='__main__':main()
